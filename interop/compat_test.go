type versionAction struct {
	name string
	from ocpp.Role
	send bool
}

func actionsOf(v ocpp.Version) []versionAction {
	var out []versionAction
	switch v {
	case ocpp.V16:
		for _, a := range ocpp16.Actions {
			out = append(out, versionAction{a.Name, a.From, a.Send})
		}
	case ocpp.V201:
		for _, a := range ocpp201.Actions {
			out = append(out, versionAction{a.Name, a.From, a.Send})
		}
	case ocpp.V21:
		for _, a := range ocpp21.Actions {
			out = append(out, versionAction{a.Name, a.From, a.Send})
		}
	}
	return out
}

// TestWriteCompatibility writes docs/compatibility/<version>.md: one matrix
// per OCPP version of every action against go-ocpp and each reference
// stack, from what the reference images declare (print-capabilities) and
// the scenarios their fixtures define (print-fixture). It runs only with
// OCPP_WRITE_COMPAT=1 (make compat), so that the documents change only
// when asked.
func TestWriteCompatibility(t *testing.T) {
	if os.Getenv("OCPP_WRITE_COMPAT") != "1" {
		t.Skip("set OCPP_WRITE_COMPAT=1 (make compat) to rewrite docs/compatibility")
	}
	refs := adapters(t)
	dir := filepath.Join("..", "docs", "compatibility")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, v := range []ocpp.Version{ocpp.V16, ocpp.V201, ocpp.V21} {
		doc := compatibilityDoc(t, v, refs)
		name := "ocpp" + strings.ReplaceAll(v.String(), ".", "") + ".md"
		if err := os.WriteFile(filepath.Join(dir, name), []byte(doc), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func compatibilityDoc(t *testing.T, v ocpp.Version, refs []adapter) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# OCPP %s: go-ocpp and the reference stacks\n\n", v)
	fmt.Fprintf(&b, "Generated by `make compat` (interop/compat_test.go) on %s; do not edit.\n", time.Now().UTC().Format("2006-01-02"))
	b.WriteString("Every action of the version, what go-ocpp does with it, and what each\n" +
		"reference stack of [ocpp-interop](https://github.com/otfabric/ocpp-interop)\n" +
		"declares for it in its container contract (`print-capabilities`): that its\n" +
		"station or CSMS sends the action, or handles it. A reference adapter\n" +
		"declares what it wires up and has verified; the upstream library may model\n" +
		"more. The last column lists the interop scenarios (fixture samples) that\n" +
		"exchange the action between go-ocpp and the references in both roles;\n" +
		"their results are in [INTEROPERABILITY.md](../../INTEROPERABILITY.md).\n\n")

	b.WriteString("| Reference | Upstream | Image | Contract | OCPP " + v.String() + " |\n|---|---|---|---|---|\n")
	type refInfo struct {
		a        adapter
		caps     *capabilities
		supports bool
		f        *fixture
	}
	var infos []refInfo
	for _, a := range refs {
		c := a.caps(t)
		vc, ok := c.Versions[v.String()]
		supports := ok && (vc.Client.Supported || vc.Server.Supported)
		ri := refInfo{a: a, caps: c, supports: supports}
		if supports {
			ri.f = a.fixture(t, v)
		}
		infos = append(infos, ri)
		state := "not supported"
		if supports {
			state = "station " + yes(vc.Client.Supported) + ", CSMS " + yes(vc.Server.Supported)
		}
		fmt.Fprintf(&b, "| %s | %s %s | `%s` | %s | %s |\n", a.name, c.Upstream.Name, c.Upstream.Version, shortImage(a.image), c.ContractVersion, state)
	}

	b.WriteString("\nCells: **sends** / **handles** as declared; — not declared; n/a the\n" +
		"reference does not support the version. go-ocpp: every action is typed,\n" +
		"validated against the OCA schema in both directions, dispatchable, and\n" +
		"exchanged in both roles between a go-ocpp station and CSMS (e2e\n" +
		"`TestMatrix`).\n\n")

	header := "| Action | Sent by | go-ocpp |"
	sep := "|---|---|---|"
	for _, ri := range infos {
		header += " " + ri.a.name + " station | " + ri.a.name + " CSMS |"
		sep += "---|---|"
	}
	b.WriteString(header + " Interop scenarios |\n" + sep + "---|\n")

	var fixtures []*fixture
	var capsOf []*capabilities
	for _, ri := range infos {
		fixtures = append(fixtures, ri.f)
		capsOf = append(capsOf, ri.caps)
	}
	actions := actionsOf(v)
	sort.Slice(actions, func(i, j int) bool { return actions[i].name < actions[j].name })
	counts := map[string][2]int{} // reference -> [station, csms] actions declared
	withScenario := 0
	for _, act := range actions {
		from := map[ocpp.Role]string{ocpp.ChargingStation: "Station", ocpp.CSMS: "CSMS", 0: "both"}[act.from]
		kind := "CALL"
		if act.send {
			kind = "SEND"
		}
		goCell := "✓ " + kind
		row := fmt.Sprintf("| %s | %s | %s |", act.name, from, goCell)
		for _, ri := range infos {
			if !ri.supports {
				row += " n/a | n/a |"
				continue
			}
			vc := ri.caps.Versions[v.String()]
			st := roleCell(vc.Client, act, ocpp.ChargingStation)
			cs := roleCell(vc.Server, act, ocpp.CSMS)
			c := counts[ri.a.name]
			if st != "—" {
				c[0]++
			}
			if cs != "—" {
				c[1]++
			}
			counts[ri.a.name] = c
			row += " " + st + " | " + cs + " |"
		}
		sc := scenarios(fixtures, act.name)
		if act.send && !anySend(capsOf, v) && sc != "—" {
			// A SEND sample runs only where a reference declares SEND.
			sc += " (no reference supports SEND: skipped)"
		} else if sc != "—" {
			withScenario++
		}
		row += " " + sc + " |"
		b.WriteString(row + "\n")
	}

	fmt.Fprintf(&b, "\n## Totals\n\n| | Actions | go-ocpp |")
	for _, ri := range infos {
		fmt.Fprintf(&b, " %s station | %s CSMS |", ri.a.name, ri.a.name)
	}
	b.WriteString("\n|---|---|---|")
	for range infos {
		b.WriteString("---|---|")
	}
	fmt.Fprintf(&b, "\n| OCPP %s | %d | %d |", v, len(actions), len(actions))
	for _, ri := range infos {
		if !ri.supports {
			b.WriteString(" n/a | n/a |")
			continue
		}
		c := counts[ri.a.name]
		fmt.Fprintf(&b, " %d | %d |", c[0], c[1])
	}
	b.WriteString("\n\nA reference's count is the actions its station or CSMS sends or handles.\n")
	fmt.Fprintf(&b, "\n%d of the %d actions are exchanged with at least one reference stack in an\n"+
		"interop scenario. The other %d are verified against go-ocpp itself (e2e) and\n"+
		"against the OCA schemas, not against an independent implementation: no\n"+
		"reference adapter declares them yet (tracked in FEATURES.md, interop gaps).\n",
		withScenario, len(actions), len(actions)-withScenario)

	var issues []string
	for k, ev := range knownIssues {
		if strings.Contains(k, "/"+v.String()+"/") {
			issues = append(issues, fmt.Sprintf("- `%s`: %s", k, ev))
		}
	}
	if len(issues) > 0 {
		sort.Strings(issues)
		b.WriteString("\n## Known upstream defects\n\nScenarios skipped because of a defect of the reference, with the evidence:\n\n" + strings.Join(issues, "\n") + "\n")
	}
	return b.String()
}

func anySend(caps []*capabilities, v ocpp.Version) bool {
	for _, c := range caps {
		if c != nil && c.Versions[v.String()].Features.Send {
			return true
		}
	}
	return false
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

func shortImage(image string) string {
	if i := strings.Index(image, "@sha256:"); i >= 0 {
		return image[:i] + "@sha256:" + image[i+8:i+20] + "…"
	}
	return image
}

// roleCell says what a reference role declares for an action: it sends it
// (when its role sends the action) or handles it (when it receives it).
func roleCell(r roleCaps, act versionAction, role ocpp.Role) string {
	if !r.Supported {
		return "—"
	}
	var parts []string
	if (act.from == role || act.from == 0) && slices.Contains(r.Sends, act.name) {
		parts = append(parts, "sends")
	}
	if (act.from != role || act.from == 0) && slices.Contains(r.Handles, act.name) {
		parts = append(parts, "handles")
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, ", ")
}

// scenarios lists the fixture samples of any reference that exchange the
// action, deduplicated.
func scenarios(fs []*fixture, action string) string {
	set := map[string]bool{}
	for _, f := range fs {
		if f == nil {
			continue
		}
		for name, s := range f.Samples {
			if s.Action == action {
				set[name] = true
			}
		}
	}
	if len(set) == 0 {
		return "—"
	}
	var names []string
	for n := range set {
		names = append(names, "`"+n+"`")
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}
