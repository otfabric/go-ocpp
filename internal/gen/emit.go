func sha256Hex(b []byte) string {
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:])
}

const header = "// Code generated by go-ocpp/internal/gen from the OCA JSON schemas. DO NOT EDIT.\n\n// SPDX-License-Identifier: MIT\n\n"

// roleConst is the ocpp.Role that sends an action, as Go source.
func roleConst(from string) string {
	switch from {
	case fromStation:
		return "ocpp.ChargingStation"
	case fromCSMS:
		return "ocpp.CSMS"
	default:
		return "0"
	}
}

// roles are the handler and dispatcher names of a version's two roles.
type roles struct {
	station, csms string // e.g. "ChargePoint", "CentralSystem"
}

func rolesOf(version string) roles {
	if version == "1.6" {
		return roles{"ChargePoint", "CentralSystem"}
	}
	return roles{"ChargingStation", "CSMS"}
}

func versionConst(version string) string {
	switch version {
	case "1.6":
		return "ocpp.V16"
	case "2.0.1":
		return "ocpp.V201"
	default:
		return "ocpp.V21"
	}
}

// asciiDocRef matches the cross-references of the OCA descriptions,
// "<<cmn_registrationstatusenumtype,Status>>", whose text is kept.
var asciiDocRef = regexp.MustCompile(`<<[^,>]*,([^>]*)>>`)

func comment(b *strings.Builder, indent, text string) {
	text = html.UnescapeString(text)
	text = asciiDocRef.ReplaceAllString(text, "$1")
	text = strings.TrimSpace(strings.ReplaceAll(text, "\r", ""))
	if text == "" {
		return
	}
	for _, line := range wrap(text, 76) {
		fmt.Fprintf(b, "%s// %s\n", indent, line)
	}
}

func wrap(s string, width int) []string {
	var out []string
	for _, para := range strings.Split(s, "\n") {
		w := strings.Fields(para)
		line := ""
		for _, x := range w {
			if line != "" && len(line)+1+len(x) > width {
				out = append(out, line)
				line = x
				continue
			}
			if line != "" {
				line += " "
			}
			line += x
		}
		if line != "" {
			out = append(out, line)
		}
	}
	return out
}

// goTypeOf is the Go type of a field.
func goTypeOf(f *field) string {
	t := f.Elem.Base
	switch t {
	case "time":
		t = "time.Time"
	case "raw":
		// Any JSON value; absent when nil.
		if f.Array {
			return "[]json.RawMessage"
		}
		return "json.RawMessage"
	}
	if f.Array {
		return "[]" + t
	}
	if !f.Required {
		return "*" + t
	}
	return t
}

func emitTypes(m *model) string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"encoding/json\"\n\t\"time\"\n\n\t\"github.com/otfabric/go-ocpp\"\n\t\"github.com/otfabric/go-ocpp/internal/wire\"\n)\n\n", m.Package)
	b.WriteString("var (\n\t_ = time.Time{}\n\t_ = json.Marshal\n)\n\n")
	fmt.Fprintf(&b, "// codes are the CALLERROR codes of OCPP %s for validation failures.\nvar codes = wire.CodesFor(%s)\n\n", m.Version, versionConst(m.Version))

	names := make([]string, 0, len(m.Types))
	for n := range m.Types {
		names = append(names, n)
	}
	// Message types too.
	for _, msg := range m.Messages {
		names = append(names, msg.Request.Name, msg.Response.Name)
	}
	sort.Strings(names)
	seen := map[string]bool{}
	types := map[string]*goType{}
	for n, t := range m.Types {
		types[n] = t
	}
	for _, msg := range m.Messages {
		types[msg.Request.Name], types[msg.Response.Name] = msg.Request, msg.Response
	}
	for _, n := range names {
		if seen[n] {
			continue
		}
		seen[n] = true
		t := types[n]
		switch {
		case t.CustomData:
			emitCustomData(&b, t)
		case t.Kind == kindEnum:
			emitEnum(&b, t)
		default:
			emitStruct(&b, t)
		}
	}
	return b.String()
}

func emitEnum(b *strings.Builder, t *goType) {
	if t.Doc != "" {
		comment(b, "", t.Name+": "+t.Doc)
	} else {
		fmt.Fprintf(b, "// %s is an enumeration of the schemas.\n", t.Name)
	}
	fmt.Fprintf(b, "type %s string\n\n// The values of %s.\nconst (\n", t.Name, t.Name)
	for _, v := range t.Values {
		fmt.Fprintf(b, "\t%s %s = %s\n", constName(t.Name, v), t.Name, strconv.Quote(v))
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "// Valid reports whether x is one of the values the schema allows.\nfunc (x %s) Valid() bool {\n\tswitch x {\n\tcase ", t.Name)
	for i, v := range t.Values {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(constName(t.Name, v))
	}
	b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
}

func emitCustomData(b *strings.Builder, t *goType) {
	fmt.Fprintf(b, `// CustomData carries vendor-specific data (the CustomDataType of the
// schemas): a vendorId, and any other properties, which the schemas allow.
type CustomData struct {
	VendorID string
	// Fields holds the other properties as raw JSON. A "vendorId" key here
	// is ignored when encoding.
	Fields map[string]json.RawMessage
}

// MarshalJSON writes the vendorId and the other properties.
func (x CustomData) MarshalJSON() ([]byte, error) {
	m := make(map[string]any, len(x.Fields)+1)
	for k, v := range x.Fields {
		m[k] = v
	}
	m["vendorId"] = x.VendorID
	return json.Marshal(m)
}

// UnmarshalJSON reads the vendorId and keeps the other properties.
func (x *CustomData) UnmarshalJSON(b []byte) error {
	if err := wire.Object(b, "", codes, []string{"vendorId"}, []string{"vendorId"}, false); err != nil {
		return err
	}
	var m map[string]json.RawMessage
	if err := json.Unmarshal(b, &m); err != nil {
		return err
	}
	var id string
	if err := json.Unmarshal(m["vendorId"], &id); err != nil {
		return wire.Invalid(codes.Type, "vendorId", "not a string")
	}
	delete(m, "vendorId")
	x.VendorID, x.Fields = id, nil
	if len(m) > 0 {
		x.Fields = m
	}
	return nil
}

// Validate checks x against its schema.
func (x *CustomData) Validate() error { return x.validate("") }

func (x *CustomData) validate(path string) error {
	return wire.MaxLength(codes, wire.Field(path, "vendorId"), x.VendorID, %d)
}

`, t.VendorMax)
}

func emitStruct(b *strings.Builder, t *goType) {
	if t.Doc != "" {
		comment(b, "", t.Name+": "+t.Doc)
	} else {
		fmt.Fprintf(b, "// %s is an object of the schemas.\n", t.Name)
	}
	fmt.Fprintf(b, "type %s struct {\n", t.Name)
	for i, f := range t.Fields {
		if i > 0 && f.Doc != "" {
			b.WriteString("\n")
		}
		comment(b, "\t", f.Doc)
		tag := f.JSON
		if !f.Required {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", f.Name, goTypeOf(f), tag)
	}
	b.WriteString("}\n\n")

	known, required := []string{}, []string{}
	for _, f := range t.Fields {
		known = append(known, strconv.Quote(f.JSON))
		if f.Required {
			required = append(required, strconv.Quote(f.JSON))
		}
	}
	fmt.Fprintf(b, `// UnmarshalJSON decodes x strictly: required properties must be present%s.
func (x *%s) UnmarshalJSON(b []byte) error {
	if err := wire.Object(b, "", codes, []string{%s}, []string{%s}, %v); err != nil {
		return err
	}
	type plain %s
	return json.Unmarshal(b, (*plain)(x))
}

`, map[bool]string{true: ", and no other property", false: ""}[t.Strict], t.Name, strings.Join(known, ", "), strings.Join(required, ", "), t.Strict, t.Name)

	fmt.Fprintf(b, "// Validate checks x against its schema.\nfunc (x *%s) Validate() error { return x.validate(\"\") }\n\n", t.Name)
	fmt.Fprintf(b, "func (x *%s) validate(path string) error {\n", t.Name)
	for _, f := range t.Fields {
		emitFieldCheck(b, f)
	}
	b.WriteString("\treturn nil\n}\n\n")
}

// emitFieldCheck writes the checks of one field.
func emitFieldCheck(b *strings.Builder, f *field) {
	p := fmt.Sprintf("wire.Field(path, %q)", f.JSON)
	v := "x." + f.Name
	if f.Array {
		if f.Required {
			fmt.Fprintf(b, "\tif %s == nil {\n\t\treturn wire.Required(codes, %s)\n\t}\n", v, p)
		}
		if f.MinItems > 0 || f.MaxItems >= 0 {
			fmt.Fprintf(b, "\tif %s != nil {\n\t\tif err := wire.Items(codes, %s, len(%s), %d, %d); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", v, p, v, f.MinItems, f.MaxItems)
		}
		body := elemCheck(f.Elem, "e", "wire.Index("+p+", i)", false)
		if body != "" {
			fmt.Fprintf(b, "\tfor i := range %s {\n\t\te := &%s[i]\n\t\t_ = e\n%s\t}\n", v, v, indent(body, "\t\t"))
		}
		return
	}
	if !f.Required {
		body := elemCheck(f.Elem, v, p, true)
		if body != "" {
			fmt.Fprintf(b, "\tif %s != nil {\n%s\t}\n", v, indent(body, "\t\t"))
		}
		return
	}
	body := elemCheck(f.Elem, v, p, false)
	if body != "" {
		b.WriteString(indent(body, "\t"))
	}
}

// elemCheck returns the checks of one value. v is an expression of the
// value's type, or of a pointer to it when ptr (or when it is a struct
// element, always addressable via e).
func elemCheck(r ref, v, p string, ptr bool) string {
	val := v
	if ptr || (v == "e" && r.Named == nil) || (v == "e" && r.Named != nil && r.Named.Kind == kindEnum) {
		val = "(*" + v + ")"
	}
	var b strings.Builder
	switch {
	case r.Named != nil && r.Named.Kind == kindEnum:
		fmt.Fprintf(&b, "if !%s.Valid() {\n\treturn wire.Enum(codes, %s, string(%s))\n}\n", val, p, val)
	case r.Named != nil:
		target := v
		if !ptr && v != "e" {
			target = "(&" + v + ")"
		}
		fmt.Fprintf(&b, "if err := %s.validate(%s); err != nil {\n\treturn err\n}\n", target, p)
	case r.Base == "string":
		if r.MaxLength != nil {
			fmt.Fprintf(&b, "if err := wire.MaxLength(codes, %s, %s, %d); err != nil {\n\treturn err\n}\n", p, val, *r.MaxLength)
		}
		if r.Format == "uri" {
			fmt.Fprintf(&b, "if err := wire.URI(codes, %s, %s); err != nil {\n\treturn err\n}\n", p, val)
		}
	case r.Base == "int" || r.Base == "float64":
		num := "float64(" + val + ")"
		if r.Minimum != nil {
			fmt.Fprintf(&b, "if err := wire.Minimum(codes, %s, %s, %v); err != nil {\n\treturn err\n}\n", p, num, *r.Minimum)
		}
		if r.Maximum != nil {
			fmt.Fprintf(&b, "if err := wire.Maximum(codes, %s, %s, %v); err != nil {\n\treturn err\n}\n", p, num, *r.Maximum)
		}
		if r.MultipleOf != nil {
			fmt.Fprintf(&b, "if err := wire.MultipleOf(codes, %s, %s, %v); err != nil {\n\treturn err\n}\n", p, num, *r.MultipleOf)
		}
	}
	return b.String()
}

func indent(s, in string) string {
	if s == "" {
		return ""
	}
	lines := strings.Split(strings.TrimSuffix(s, "\n"), "\n")
	for i, l := range lines {
		lines[i] = in + l
	}
	return strings.Join(lines, "\n") + "\n"
}

func emitActions(m *model) string {
	var b strings.Builder
	r := rolesOf(m.Version)
	vc := versionConst(m.Version)
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"context\"\n\t\"encoding/json\"\n\n\t\"github.com/otfabric/go-ocpp\"\n\t\"github.com/otfabric/go-ocpp/internal/wire\"\n)\n\n", m.Package)

	fmt.Fprintf(&b, `// Action is an action of OCPP %s and the role that sends it; From is zero
// for an action both roles send.
type Action struct {
	Name string
	From ocpp.Role
}

// ValidateRequest decodes and validates a request payload of action, as a
// dispatcher would. It returns a *ocpp.ValidationError for an invalid
// payload, and an error for an action OCPP %s does not define.
func ValidateRequest(action string, payload json.RawMessage) error {
	m := newRequest(action)
	if m == nil {
		return ocpp.NewCallError(ocpp.NotImplemented, action+" is not an action of OCPP %s")
	}
	return wire.Decode(payload, m, codes)
}

// ValidateResponse decodes and validates a response payload of action.
func ValidateResponse(action string, payload json.RawMessage) error {
	m := newResponse(action)
	if m == nil {
		return ocpp.NewCallError(ocpp.NotImplemented, action+" is not an action of OCPP %s")
	}
	return wire.Decode(payload, m, codes)
}

`, m.Version, m.Version, m.Version, m.Version)
	// The action table.
	fmt.Fprintf(&b, "// Actions lists every action of OCPP %s, with the role that sends it\n// (zero for DataTransfer, which both send).\nvar Actions = []Action{\n", m.Version)
	for _, msg := range m.Messages {
		fmt.Fprintf(&b, "\t{Name: %q, From: %s},\n", msg.Action, roleConst(msg.From))
	}
	b.WriteString("}\n\n")

	// Factories for raw use.
	b.WriteString("func newRequest(action string) wire.Message {\n\tswitch action {\n")
	for _, msg := range m.Messages {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn new(%s)\n", msg.Action, msg.Request.Name)
	}
	b.WriteString("\t}\n\treturn nil\n}\n\n")
	b.WriteString("func newResponse(action string) wire.Message {\n\tswitch action {\n")
	for _, msg := range m.Messages {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn new(%s)\n", msg.Action, msg.Response.Name)
	}
	b.WriteString("\t}\n\treturn nil\n}\n\n")

	// Call functions.
	for _, msg := range m.Messages {
		who := map[string]string{fromStation: "the " + r.station, fromCSMS: "the " + r.csms, fromBoth: "either role"}[msg.From]
		fmt.Fprintf(&b, "// %s sends a %s CALL (sent by %s) and returns its response.\n// The request is validated before it is sent, and the response when it arrives.\n", msg.Action, msg.Action, who)
		fmt.Fprintf(&b, "func %s(ctx context.Context, c ocpp.Caller, req *%s) (*%s, error) {\n", msg.Action, msg.Request.Name, msg.Response.Name)
		fmt.Fprintf(&b, "\tresp := new(%s)\n\tif err := wire.Call(ctx, c, %s, %s, %q, req, resp); err != nil {\n\t\treturn nil, err\n\t}\n\treturn resp, nil\n}\n\n", msg.Response.Name, vc, roleConst(msg.From), msg.Action)
	}

	// Call functions by name, for raw use and tests.
	b.WriteString("// callByName calls the call function of an action with a request of its\n// type.\nvar callByName = map[string]func(context.Context, ocpp.Caller, wire.Message) (wire.Message, error){\n")
	for _, msg := range m.Messages {
		fmt.Fprintf(&b, "\t%q: func(ctx context.Context, c ocpp.Caller, req wire.Message) (wire.Message, error) {\n\t\treturn %s(ctx, c, req.(*%s))\n\t},\n", msg.Action, msg.Action, msg.Request.Name)
	}
	b.WriteString("}\n\n")

	emitRole(&b, m, r.csms, fromStation, "CALLs a "+strings.ToLower(spaced(r.station))+" sends")
	emitRole(&b, m, r.station, fromCSMS, "CALLs a "+spaced(r.csms)+" sends")
	return b.String()
}

func spaced(s string) string {
	if s == "CSMS" {
		return "CSMS"
	}
	return strings.Join(words(s), " ")
}

// emitRole writes the handler interface, its Unimplemented struct and the
// dispatcher of the role that receives the actions sent from "from".
func emitRole(b *strings.Builder, m *model, role, from, what string) {
	var recv []*message
	for _, msg := range m.Messages {
		if msg.From == from || msg.From == fromBoth {
			recv = append(recv, msg)
		}
	}
	fmt.Fprintf(b, "// %sHandler handles the %s. Embed\n// Unimplemented%sHandler to answer the actions an application does not\n// handle with NotSupported, and to keep compiling when methods are added.\n", role, what, role)
	fmt.Fprintf(b, "type %sHandler interface {\n", role)
	for _, msg := range recv {
		fmt.Fprintf(b, "\t%s(ctx context.Context, p ocpp.Peer, req *%s) (*%s, error)\n", msg.Action, msg.Request.Name, msg.Response.Name)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// Unimplemented%sHandler answers every action with the CALLERROR\n// NotSupported.\ntype Unimplemented%sHandler struct{}\n\n", role, role)
	for _, msg := range recv {
		fmt.Fprintf(b, "// %s answers NotSupported.\nfunc (Unimplemented%sHandler) %s(context.Context, ocpp.Peer, *%s) (*%s, error) {\n\treturn nil, ocpp.NewCallError(ocpp.NotSupported, \"\")\n}\n\n", msg.Action, role, msg.Action, msg.Request.Name, msg.Response.Name)
	}
	lower := strings.ToLower(role[:1]) + role[1:]
	if role == "CSMS" {
		lower = "csms"
	}
	fmt.Fprintf(b, `// %s returns the dispatcher for a %s: it decodes and validates each
// incoming CALL, calls h, and validates and encodes the response. An invalid
// request is answered with the CALLERROR its violation calls for; an action
// this role sends but does not receive with NotSupported; an action OCPP %s
// does not define with NotImplemented.
func %s(h %sHandler) ocpp.Dispatcher { return %sDispatcher{h} }

type %sDispatcher struct{ h %sHandler }

func (d %sDispatcher) Dispatch(ctx context.Context, p ocpp.Peer, action string, payload json.RawMessage) (json.RawMessage, error) {
	switch action {
`, role, spaced(role), m.Version, role, role, lower, lower, role, lower)
	for _, msg := range recv {
		fmt.Fprintf(b, "\tcase %q:\n\t\treq := new(%s)\n\t\tif err := wire.Request(payload, req, codes); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tresp, err := d.h.%s(ctx, p, req)\n\t\treturn wire.Respond(action, resp, resp == nil, err)\n", msg.Action, msg.Request.Name, msg.Action)
	}
	b.WriteString("\t}\n\tif newRequest(action) != nil {\n\t\treturn nil, ocpp.NewCallError(ocpp.NotSupported, action+\" is not sent to this role\")\n\t}\n\treturn nil, ocpp.NewCallError(ocpp.NotImplemented, \"\")\n}\n\n")
}

// emitCoverage writes coverage.json.
func emitCoverage(m *model, rel func(string) string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "{\n  \"version\": %q,\n  \"package\": %q,\n  \"actions\": [\n", m.Version, m.Package)
	for i, msg := range m.Messages {
		from := map[string]string{fromStation: "ChargingStation", fromCSMS: "CSMS", fromBoth: "both"}[msg.From]
		fmt.Fprintf(&b, "    {\"action\": %q, \"from\": %q, \"request\": %q, \"response\": %q, \"requestSchema\": %q, \"requestSchemaSha256\": %q, \"responseSchema\": %q, \"responseSchemaSha256\": %q, \"typed\": true, \"validated\": true, \"dispatchable\": true}",
			msg.Action, from, msg.Request.Name, msg.Response.Name, rel(msg.RequestFile), msg.RequestHash, rel(msg.ResponseFile), msg.ResponseHash)
		if i < len(m.Messages)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("  ]\n}\n")
	return b.String()
}
